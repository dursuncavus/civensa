spec = importlib.util.spec_from_file_location('prototype_contrast', ROOT / 'docs/design/prototype/check_contrast.py')
contrast = importlib.util.module_from_spec(spec)
spec.loader.exec_module(contrast)
# Reuse the approved alpha compositing, font thresholds, borders and focus collector.
# Scope to the rollout; legacy content is deliberately outside this contrast audit.
COLLECT = contrast.COLLECT.replace(
    "const modal = document.querySelector('dialog[open]');\n  const scope = modal || document.body;",
    "const modal = document.querySelector('#passwordModal:not([hidden]) .modal-card');\n"
    "  const scopes = modal ? [modal] : [...document.querySelectorAll("
    "'.sidebar,.topbar,.page-header,.notification-panel:not([hidden]),.module-list,#toast.show,.skip')];")
COLLECT = COLLECT.replace("[scope, ...scope.querySelectorAll('*')]",
                          "scopes.flatMap(scope => [scope, ...scope.querySelectorAll('*')])")
COLLECT = COLLECT.replace('.button, summary, .step-number', '.button, .shell-button, .nav-link, .mobile-nav, summary, .step-number')
TOKENS = {tuple(bytes.fromhex(v)): '--' + k for k, v in re.findall(
    r'--([\w-]+):\s*#([\da-fA-F]{6})', (ROOT / 'app/static/design/tokens.css').read_text())}
SELECTED = {'034-modules-department.png', '033-modules-strategy.png',
            '024-department-department.png', '012-activity-sections-department.png',
            '039-report-builder-strategy.png'}


def signature(control):
    """All original elements, duplicates included, retain label, identity and target."""
    control = dict(control)
    # The prototype removes CSS uppercase from these unchanged Turkish labels.
    labels = {'MEVCUT PAROLA': 'Mevcut parola', 'YENİ PAROLA': 'Yeni parola',
              'YENİ PAROLA TEKRAR': 'Yeni parola tekrar'}
    if control.get('id') in {'currentPassword', 'newPassword', 'confirmPassword'}:
        control['label'] = labels.get(control['label'], control['label'])
    # Explicit type=button on non-form shell actions has the same target.
    if control.get('id') in {'cancelPasswordChange', 'savePasswordChange'}:
        control['type'] = 'button'
    # Fixture timestamps are generated by ui_setup on each replay. Only that
    # clock-dependent text is normalized; labels, IDs and targets remain exact.
    return tuple(re.sub(r'\d{2}\.\d{2}\.\d{4} \d{2}:\d{2} TSİ', '<yayın zamanı>',
                        str(control.get(k, '')))
                 for k in ('tag', 'label', 'id', 'name', 'type', 'target'))


LAYOUT = r"""() => {
  const width = document.documentElement.clientWidth;
  const visible = el => el.getClientRects().length && getComputedStyle(el).visibility !== 'hidden' && !el.closest('[hidden]');
  const overflow = [...document.querySelectorAll('body *')].filter(el => {
    if (!visible(el) || el.closest('.skip,.sr-only,script,style')) return false;
    const r = el.getBoundingClientRect();
    if (r.left >= -1 && r.right <= width + 1) return false;
    // Scrolling tables/years retain their full controls within their local scrollport.
    for (let p = el.parentElement; p && p !== document.body; p = p.parentElement) {
      const s = getComputedStyle(p), pr = p.getBoundingClientRect();
      if (['auto','scroll'].includes(s.overflowX) && pr.left >= -1 && pr.right <= width + 1) return false;
    }
    return true;
  }).map(el => ({tag:el.tagName,id:el.id,classes:el.className?.baseVal ?? el.className}));
  const modal = document.querySelector('.modal:not([hidden]),dialog[open]');
  const scope = modal || document.body;
  const describe = el => el.id || el.getAttribute('aria-label') || el.textContent.trim().slice(0,70) || el.tagName;
  const clipped = [], controls = [];
  for (const el of scope.querySelectorAll('a,button,input:not([type=hidden]),select,textarea,summary')) {
    if (!visible(el) || el.closest('.skip,.sr-only,[inert]')) continue;
    let {left,right,top,bottom} = el.getBoundingClientRect();
    for (let p = el.parentElement; p && p !== document.body; p = p.parentElement) {
      const s = getComputedStyle(p), r = p.getBoundingClientRect();
      if (['hidden','clip'].includes(s.overflowX) && (left < r.left-1 || right > r.right+1)) clipped.push(describe(el));
      if (['hidden','clip'].includes(s.overflowY) && (top < r.top-1 || bottom > r.bottom+1)) clipped.push(describe(el));
      if (['auto','scroll','hidden','clip'].includes(s.overflowX)) { left=Math.max(left,r.left); right=Math.min(right,r.right); }
      if (['auto','scroll','hidden','clip'].includes(s.overflowY)) { top=Math.max(top,r.top); bottom=Math.min(bottom,r.bottom); }
    }
    if (right-left > 1 && bottom-top > 1) controls.push({el, rects:[...el.getClientRects()].map(r => ({
      left:Math.max(left,r.left), right:Math.min(right,r.right), top:Math.max(top,r.top), bottom:Math.min(bottom,r.bottom)
    }))});
  }
  const overlaps = [];
  for (let i=0; i<controls.length; i++) for (let j=i+1; j<controls.length; j++) {
    const a=controls[i],b=controls[j];
    if (a.el.contains(b.el) || b.el.contains(a.el)) continue;
    // Inline links may wrap across lines. Their union boxes overlap even when
    // the actual line fragments do not; compare painted fragments instead.
    if (a.rects.some(ar => b.rects.some(br => Math.min(ar.right,br.right)-Math.max(ar.left,br.left)>2 && Math.min(ar.bottom,br.bottom)-Math.max(ar.top,br.top)>2)))
      overlaps.push([describe(a.el),describe(b.el)]);
  }
  const shell_issues = [];
  const workspace = document.querySelector('.workspace'), sidebar = document.querySelector('.sidebar');
  if (workspace && sidebar) {
    const w=workspace.getBoundingClientRect(), s=sidebar.getBoundingClientRect();
    if (width <= 700 && (Math.abs(w.width-width)>1 || s.top<w.bottom-1)) shell_issues.push('Mobil içerik tam genişlikte değil veya menü içerikten sonra değil.');
    if (width > 700 && (Math.abs(s.width-248)>1 || s.height<document.querySelector('.app-shell').getBoundingClientRect().height-1)) shell_issues.push('Masaüstü menü 248 px veya tam boy değil.');
  }
  return {viewport:width, document:document.documentElement.scrollWidth, overflow, clipped, overlaps, shell_issues};
}"""


def collect_contrast(page):
    rows = page.evaluate(COLLECT)
    for selector in ('.nav-link[aria-current]', '.nav-link', '.shell-button', '.module .shell-button', '.mobile-nav'):
        candidate = page.locator(selector).filter(visible=True).first
        if candidate.count():
            candidate.hover()
            candidate.focus()
            rows += page.evaluate(COLLECT)
    page.locator('#notificationButton').click()
    rows += page.evaluate(COLLECT)
    page.locator('#closeNotifications').click()
    # Exercise the unread badge/toast presentation without issuing a write request.
    page.evaluate("document.getElementById('notificationBadge').hidden=false; document.getElementById('toast').textContent='Örnek bildirim'; document.getElementById('toast').classList.add('show')")
    rows += page.evaluate(COLLECT)
    page.evaluate("document.getElementById('notificationBadge').hidden=true; document.getElementById('toast').classList.remove('show')")
    page.locator('#changePasswordButton').click()
    rows += page.evaluate(COLLECT)
    for selector in ('#currentPassword', '#cancelPasswordChange', '#savePasswordChange'):
        page.locator(selector).hover()
        page.locator(selector).focus()
        rows += page.evaluate(COLLECT)
    page.keyboard.press('Escape')
    assert page.locator('#passwordModal').is_hidden()
    assert page.locator('#changePasswordButton').evaluate('el => el === document.activeElement')
    page.evaluate('document.activeElement.blur(); window.scrollTo(0,0)')
    return rows


def main():
    def interrupted(*_):
        raise KeyboardInterrupt
    signal.signal(signal.SIGINT, interrupted)
    signal.signal(signal.SIGTERM, interrupted)
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--capture-out', type=Path, default=Path('/tmp/civ096-captures'))
    parser.add_argument('--width', type=int, choices=(1440, 390), action='append')
    args = parser.parse_args()
    baseline = {s['filename']: s for s in json.loads(
        (ROOT / 'docs/screenshots/ui-map-v1/screens.json').read_text())['screens']}
    report, pairs = [], {}
    setup = guide.ui_setup
    for width in args.width or (1440, 390):
        def verify(page, shot, meta):
            old = baseline[shot.filename]['dom']['controls']
            current = meta['dom']['controls']
            for c in current:
                c['target'] = guide.ui_control(c)[0]
            missing = Counter(map(signature, old)) - Counter(map(signature, current))
            layout = page.evaluate(LAYOUT)
            result = dict(filename=shot.filename, width=width, elements=len(old),
                          missing=list(missing.elements()), **layout)
            report.append(result)
            if missing or layout['document'] > width or layout['overflow'] or layout['clipped'] or layout['overlaps'] or layout['shell_issues']:
                print('VERIFY ' + json.dumps(result, ensure_ascii=False), flush=True)
            # Audit actual rendered shell on both role variants, including dialogs.
            if page.locator('.app-shell').count():
                rows = collect_contrast(page) if shot.filename in {
                    '034-modules-department.png', '033-modules-strategy.png'} else page.evaluate(COLLECT)
                for row in rows:
                    fg, bg = tuple(row['color']), tuple(row['bg'])
                    key = (TOKENS.get(fg, str(fg)), TOKENS.get(bg, str(bg)), row['kind'])
                    pairs[key] = dict(ratio=contrast.ratio(fg,bg), minimum=row['minimum'], example=row['example'])
                    assert fg in TOKENS and bg in TOKENS, f'Token dışı renk: {row}'
        def setup_with_verification(engine):
            data = setup(engine)
            data['_verify_page'] = verify
            return data
        guide.ui_setup = setup_with_verification
        folder = args.capture_out / str(width)
        folder.mkdir(parents=True, exist_ok=True)
        code = guide.ui_main(SimpleNamespace(out=folder, viewport_width=width), local_test_url())
        if code:
            return code
        produced = json.loads((folder / 'screens.json').read_text())['screens']
        assert {s['filename'] for s in produced} == set(baseline), 'Ekran envanteri değişti.'
        for name in SELECTED:
            source = folder / name
            assert source.exists(), name
            shutil.copyfile(source, OUT / f'{source.stem}-{width}.png')
    failures = [r for r in report if r['missing'] or r['document'] > r['width'] or
                r['overflow'] or r['clipped'] or r['overlaps'] or r['shell_issues']]
    (OUT / 'capture-summary.json').write_text(json.dumps(dict(
        browser=json.loads((folder / 'screens.json').read_text())['browser'],
        captures=len(report), elements=sum(r['elements'] for r in report),
        failures=len(failures), screens=report), ensure_ascii=False, indent=2) + '\n')
    lines = ['| Ön plan | Arka plan | Kullanım | Oran | AA eşiği | Sonuç |',
             '| --- | --- | --- | ---: | ---: | --- |']
    contrast_failures = 0
    for (fg,bg,kind), row in sorted(pairs.items()):
        passed = row['ratio'] >= row['minimum']
        contrast_failures += not passed
        lines.append(f"| `{fg}` | `{bg}` | {kind} | {row['ratio']:.2f}:1 | {row['minimum']:g}:1 | {'Geçti' if passed else 'KALDI'} |")
    lines += ['', f'{len(pairs)} kullanım çifti · {contrast_failures} başarısız.']
    (OUT / 'contrast.md').write_text('\n'.join(lines) + '\n')
    from PIL import Image
    screenshots = []
    for width in args.width or (1440, 390):
        for name in sorted(SELECTED):
            file = OUT / f'{Path(name).stem}-{width}.png'
            with Image.open(file) as png:
                screenshots.append(dict(file=file.name, width=png.width, height=png.height,
                                        bytes=file.stat().st_size))
    (OUT / 'screenshots.json').write_text(json.dumps(screenshots, ensure_ascii=False, indent=2) + '\n')
    print(f'{len(report)} captures; {len(failures)} element/layout failures; {contrast_failures} contrast failures.')
    return bool(failures or contrast_failures)


if __name__ == '__main__':
    raise SystemExit(main())
